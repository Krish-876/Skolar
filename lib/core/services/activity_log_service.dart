import 'package:flutter_riverpod/flutter_riverpod.dart';

/// Write-path for focus session completions.
///
/// The concrete [ActivityLogServiceImpl] writes to `activity_log` via
/// Supabase. The interface contract:
///   - derives user_id from the Supabase session (NOT a parameter)
///   - accepts a client-supplied [clientId] (uuid) for idempotency:
///     the same id retried after a network failure produces ON CONFLICT DO NOTHING
///   - logs FOCUS-ONLY seconds — the caller must subtract break time
///   - completed_on is the device-local date at call time (no timezone column)
///   - append-only: no update or delete
abstract class ActivityLogService {
  /// Logs a completed or user-stopped focus session.
  ///
  /// [durationSeconds] — focus-only seconds (> 0). Break seconds must NOT be included.
  /// [clientId]        — a v4 UUID generated by the caller; re-sending the
  ///                     same UUID is a no-op (ON CONFLICT DO NOTHING).
  ///
  /// Throws [ActivityLogFailure] on write error so the caller can surface it.
  Future<void> logFocusSession({
    required int durationSeconds,
    required String clientId,
  });
}

/// Thrown when the Supabase insert fails.
class ActivityLogFailure implements Exception {
  final String message;
  const ActivityLogFailure(this.message);
  @override
  String toString() => 'ActivityLogFailure: $message';
}

/// Minimum duration in seconds required for a session to be logged and counted
/// toward hours/heatmap. Defaults to 60s matching the global nova_config threshold.
final focusMinDurationSecondsProvider = Provider<int>((ref) => 60);
